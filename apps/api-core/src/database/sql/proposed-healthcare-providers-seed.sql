-- ============================================================
-- Catálogo inicial de prestadores de salud (coverage.healthcare_providers)
-- — dos fuentes, ambas pasadas por el usuario, no inventadas:
--
-- 1. Padrón oficial de Obras Sociales de Argentina (RNOS — Registro
--    Nacional de Obras Sociales), con su código oficial. País siempre
--    Argentina (el usuario aclaró que el padrón que pasó no traía la
--    columna país, pero es el registro argentino).
-- 2. Prepagas/hospitales conocidos por su marca comercial (OSDE,
--    Swiss Medical, Hospital Italiano, etc.) — sin código oficial
--    (code queda NULL), porque un viajero las reconoce por ese
--    nombre, no por el nombre legal de la obra social que puedan
--    tener detrás. Se excluyen ASE y PAMI de este segundo bloque
--    porque ya vienen con su código oficial en el primero.
--
-- Punto de partida editable después desde "Prestadores y planes de
-- salud" — no es exhaustivo, y quedan algunos duplicados reales del
-- padrón oficial a propósito (ej. "OS.A.M." y "OSAM" son la misma
-- entidad con dos altas separadas en el padrón real) — se resuelven
-- con la acción "Fusionar con existente" cuando haga falta, no acá.
-- ============================================================

